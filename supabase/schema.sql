create table if not exists public.eventos (
  id bigint generated by default as identity primary key,
  titulo varchar(150) not null,
  descricao text,
  data_evento varchar(10) not null,
  local varchar(100) not null
);

alter table public.eventos enable row level security;

drop policy if exists "eventos leitura publica" on public.eventos;
create policy "eventos leitura publica" on public.eventos for select to anon, authenticated using (true);

drop policy if exists "eventos cadastro publico" on public.eventos;
create policy "eventos cadastro publico" on public.eventos for insert to anon, authenticated with check (true);

